    let raw: Vec<u8> = vec![
        0x1e, 0x01, 0x00, 0x00, 0x18, 0x00, 0x01, 0x80, 0x08, 0x00, 0x01, 0x00,
        0xa4, 0x00, 0x00, 0x00, 0x09, 0x00, 0x02, 0x00, 0x73, 0x69, 0x6d, 0x31,
        0x00, 0x00, 0x00, 0x00, 0x2c, 0x00, 0x02, 0x80, 0x04, 0x00, 0x01, 0x00,
        0x08, 0x00, 0x02, 0x00, 0x7d, 0x00, 0x00, 0x00, 0x1c, 0x00, 0x03, 0x80,
        0x18, 0x00, 0x01, 0x80, 0x08, 0x00, 0x01, 0x00, 0x33, 0x00, 0x00, 0x00,
        0x0a, 0x00, 0x02, 0x00, 0x42, 0x41, 0x53, 0x45, 0x52, 0x00, 0x00, 0x00,
        0x05, 0x00, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x08, 0x00, 0x04, 0x00,
        0x33, 0x00, 0x00, 0x00,
    ];

    // ethtool --show-fec sim1 after ethtool --set-fec sim1 encoding baser
